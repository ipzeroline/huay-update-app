export function getAllArticles(): BlogArticle[] {
  return [...ARTICLES].sort(
    (a, b) => new Date(b.date).getTime() - new Date(a.date).getTime(),
  )
}

export function getLatestArticles(n: number): BlogArticle[] {
  return getAllArticles().slice(0, n)
}

export function getArticle(slug: string): BlogArticle | undefined {
  return ARTICLES.find(a => a.slug === slug || a.alternateSlug === slug)
}

export function getAllSlugs(): string[] {
  return ARTICLES.flatMap(a => [a.slug, a.alternateSlug])
}

export function getRelatedArticles(slug: string): BlogArticle[] {
  const article = getArticle(slug)
  if (!article) return []
  return article.relatedSlugs
    .map(s => getArticle(s))
    .filter((a): a is BlogArticle => a != null)
}

export interface FaqEntry {
  question: string
  answer: string
}

/** Extract FAQ Q&A pairs from article HTML content */
export function extractFaq(content: string): FaqEntry[] {
  const faqs: FaqEntry[] = []
  // match <h3>Question</h3><p>Answer.</p> pattern after "คำถามที่พบบ่อย"
  const faqSection = content.split('คำถามที่พบบ่อย').pop()
  if (!faqSection) return faqs

  const qaRegex = /<h3>([^<]+)<\/h3>\s*<p>([^<]+)<\/p>/g
  let match
  while ((match = qaRegex.exec(faqSection)) !== null) {
    faqs.push({ question: match[1].trim(), answer: match[2].trim() })
  }
  return faqs
}
